export function listAutomationCenterCatalog(): AutomationDefinition[] {
  return [...AUTOMATION_CENTER_CATALOG];
}

export function getAutomationDefinitionById(id: string): AutomationDefinition | undefined {
  return AUTOMATION_CENTER_CATALOG.find((item) => item.id === id);
}

export function automationAllowsProfessionalRole(
  automation: AutomationDefinition,
  role: Extract<AutomationProfessionalRole, 'nutricionista' | 'personal_trainer'>,
): boolean {
  if (role === 'nutricionista') return automation.allowNutriActivation === true;
  return automation.allowPersonalActivation === true;
}

export function listProfessionalActivatableCatalog(
  role: Extract<AutomationProfessionalRole, 'nutricionista' | 'personal_trainer'>,
): AutomationDefinition[] {
  return listAutomationCenterCatalog().filter((item) => automationAllowsProfessionalRole(item, role));
}
